export const ADMIN_SUB_ROLES = {
  SUPER_ADMIN: 'SUPER_ADMIN',
  SUPPORT: 'SUPPORT',
  FINANCE: 'FINANCE',
  OPS: 'OPS',
};

export const PERMISSION_RESOURCES = {
  USERS: 'users',
  VENDORS: 'vendors',
  KYC: 'kyc',
  BOOKINGS: 'bookings',
  ORDERS: 'orders',
  WALLETS: 'wallets',
  REPORTS: 'reports',
  SETTINGS: 'settings',
  ADMINS: 'admins',
};

export const PERMISSION_ACTIONS = {
  READ: 'READ',
  CREATE: 'CREATE',
  UPDATE: 'UPDATE',
  DELETE: 'DELETE',
  BLOCK: 'BLOCK',
  APPROVE: 'APPROVE',
  REJECT: 'REJECT',
  EXPORT: 'EXPORT',
};

const ALL_ACTIONS = Object.values(PERMISSION_ACTIONS);
const ALL_RESOURCES = Object.values(PERMISSION_RESOURCES);

/**
 * Fixed, hardcoded permission sets per admin sub-role — not stored per-document.
 * checkPermission() resolves against this map at request time.
 */
export const ADMIN_SUB_ROLE_PERMISSIONS = {
  [ADMIN_SUB_ROLES.SUPER_ADMIN]: Object.fromEntries(ALL_RESOURCES.map((resource) => [resource, ALL_ACTIONS])),

  [ADMIN_SUB_ROLES.SUPPORT]: {
    [PERMISSION_RESOURCES.USERS]: [PERMISSION_ACTIONS.READ, PERMISSION_ACTIONS.UPDATE, PERMISSION_ACTIONS.BLOCK],
    [PERMISSION_RESOURCES.VENDORS]: [PERMISSION_ACTIONS.READ, PERMISSION_ACTIONS.UPDATE, PERMISSION_ACTIONS.BLOCK],
    [PERMISSION_RESOURCES.KYC]: [PERMISSION_ACTIONS.READ],
  },

  [ADMIN_SUB_ROLES.FINANCE]: {
    [PERMISSION_RESOURCES.WALLETS]: [PERMISSION_ACTIONS.READ, PERMISSION_ACTIONS.UPDATE],
    [PERMISSION_RESOURCES.ORDERS]: [PERMISSION_ACTIONS.READ, PERMISSION_ACTIONS.UPDATE],
    [PERMISSION_RESOURCES.REPORTS]: [PERMISSION_ACTIONS.READ, PERMISSION_ACTIONS.EXPORT],
  },

  [ADMIN_SUB_ROLES.OPS]: {
    [PERMISSION_RESOURCES.BOOKINGS]: [PERMISSION_ACTIONS.READ, PERMISSION_ACTIONS.UPDATE, PERMISSION_ACTIONS.APPROVE],
    [PERMISSION_RESOURCES.VENDORS]: [PERMISSION_ACTIONS.READ, PERMISSION_ACTIONS.UPDATE],
    [PERMISSION_RESOURCES.KYC]: [PERMISSION_ACTIONS.READ, PERMISSION_ACTIONS.APPROVE, PERMISSION_ACTIONS.REJECT],
  },
};
